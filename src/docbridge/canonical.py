"""The canonical representation every extractor produces and every check reads.

Four formats, one shape. A document is an ordered list of blocks; a block is an
ordered list of segments; every segment says where its text came from
(`Origin`). Comparison never looks at a format directly - only at this.

Two ideas carry the design:

* ORIGIN, so formats that disagree about what is "text" can still be compared.
  A DOCX list label "1." is generated by the numbering engine; in a PDF the same
  "1." is a literal character. Both land here as text, but tagged, so a
  comparison can include or exclude a class of text for a given format pair
  instead of guessing (see compare.stream_origins).

* UNKNOWN, so a construct docbridge cannot read is never read as absence. A PDF
  page with a picture of text and no text layer, an equation, an embedded
  object: each becomes a SENTINEL token. A sentinel never equals anything - not
  even another sentinel - so no comparison can pass across it, and a difference
  that touches one is reported as NOT_CHECKED rather than PASS or FAIL
  (METHODOLOGY R1, R19: a value failing its predicate is absent, absence is
  UNKNOWN, UNKNOWN is never a positive finding).
"""
from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass, field
from enum import Enum

from . import normalize as N

# \S in a str pattern is exactly "not str.isspace()" (both use CPython's
# _PyUnicode_IsWhitespace), so this splits identically to str.split().
_NON_SPACE = re.compile(r"\S+")


class Origin(str, Enum):
    CONTENT = "content"
    LIST_LABEL = "list_label"      # an ordinal label a numbering engine renders ("1.", "a)", "1.2.")
    IMAGE_ALT = "image_alt"        # an image's alternative text
    NOTE_REF = "note_ref"          # a footnote/endnote reference, rendered "[n]"
    NOTE = "note"                  # footnote/endnote body, appended after the body text
    RUBY = "ruby"                  # DOCX guide text shown above its base text (w:rt); always compared
    FURNITURE = "furniture"        # page headers and footers
    UNKNOWN = "unknown"            # present, not readable by docbridge -> sentinel


class BlockKind(str, Enum):
    PARAGRAPH = "paragraph"
    HEADING = "heading"
    LIST_ITEM = "list_item"
    TABLE_CELL = "table_cell"
    CODE = "code"
    QUOTE = "quote"
    NOTE = "note"
    FURNITURE = "furniture"
    TEXTBOX = "textbox"
    UNREADABLE = "unreadable"


@dataclass
class Segment:
    text: str
    origin: Origin = Origin.CONTENT
    reason: str | None = None       # a contract.Reason value, for UNKNOWN segments


@dataclass
class Block:
    kind: BlockKind
    segments: list[Segment] = field(default_factory=list)
    page: int | None = None
    level: int | None = None        # heading level 1..9
    list_depth: int | None = None   # 0-based nesting depth
    ordered: bool | None = None
    table: int | None = None
    row: int | None = None
    col: int | None = None
    locator: str | None = None      # human-readable position: "line 14", "p.3", "table 2 r1c2"
    line: int | None = None         # Markdown: 1-based source line the block starts on
    # A list item that also has another role - a table cell, a text box, a
    # heading, a note paragraph - keeps that kind and carries its list role
    # here (with list_depth and ordered). Audit W2 (2026-09-27): a DOCX list in
    # a cell or text box was no list item, so removing it passed.
    list_item: bool = False

    def add(self, text: str, origin: Origin = Origin.CONTENT, reason: str | None = None) -> None:
        if text or origin is Origin.UNKNOWN:
            self.segments.append(Segment(text, origin, reason))

    def text(self, origins: frozenset[Origin] | None = None) -> str:
        return "".join(s.text for s in self.segments
                       if s.origin is not Origin.UNKNOWN and (origins is None or s.origin in origins))

    def has_unknown(self) -> bool:
        return any(s.origin is Origin.UNKNOWN for s in self.segments)


class Sentinel:
    """An UNKNOWN token. Equality is identity, so a sentinel matches nothing."""

    __slots__ = ("reason", "where")

    def __init__(self, reason: str, where: str):
        self.reason = reason
        self.where = where

    def __repr__(self) -> str:
        return f"<UNKNOWN {self.reason} at {self.where}>"


@dataclass
class Tok:
    value: str | Sentinel          # the full token (text view) or a sentinel
    core: str                      # the token without edge punctuation ("" for sentinels)
    classes: tuple[str, ...]
    block: int
    page: int | None
    index: int                     # position in the text-token stream
    origin: Origin

    @property
    def known(self) -> bool:
        return not isinstance(self.value, Sentinel)

    def display(self) -> str:
        return self.value if isinstance(self.value, str) else f"<{self.value.reason}>"


@dataclass
class PageInfo:
    number: int                     # 1-based
    rotation: int | None = None
    width: float | None = None
    height: float | None = None
    text_layer: str = "unknown"     # present | absent | blank | unknown
    chars: int = 0
    images: int = 0
    invisible_text: bool = False


@dataclass
class Cell:
    row: int
    col: int
    text: str
    rowspan: int = 1
    colspan: int = 1


@dataclass
class Table:
    index: int
    rows: int
    cols: int
    cells: list[Cell]
    page: int | None = None
    source: str = ""                # "markdown_pipe" | "html" | "docx"


@dataclass
class Link:
    target: str
    text: str
    block: int | None = None
    page: int | None = None


@dataclass
class Emphasis:
    kind: str                       # "strong" | "em"
    text: str
    block: int


@dataclass
class Warn:
    code: str
    message: str
    location: str | None = None


@dataclass
class Construct:
    """Something present in the document that the canonical form does not carry
    into comparison. Reported with a count so its absence is visible."""
    kind: str
    count: int
    detail: str


@dataclass
class Canonical:
    format: str
    path: str
    sha256: str
    size_bytes: int
    extractor: str                  # what read it - the oracle, named (METHODOLOGY R7)
    blocks: list[Block] = field(default_factory=list)
    pages: list[PageInfo] | None = None
    tables: list[Table] = field(default_factory=list)
    links: list[Link] = field(default_factory=list)
    emphasis: list[Emphasis] = field(default_factory=list)
    images: list[dict] = field(default_factory=list)
    outline: list[list] | None = None          # PDF bookmarks [level, title, page]
    annotations: dict[str, int] = field(default_factory=dict)
    warnings: list[Warn] = field(default_factory=list)
    unsupported: list[Construct] = field(default_factory=list)
    page_markers: int | None = None            # Markdown: docbridge page markers seen
    # Structure the reader saw but could not model, per structure check
    # ("headings", "lists", "tables", "emphasis"), with where it sits. That
    # check cannot pass: an incomplete inventory is not a verified one.
    structure_unknown: dict[str, list[str]] = field(default_factory=dict)

    def structure_gap(self, check: str, where: str) -> None:
        self.structure_unknown.setdefault(check, []).append(where)

    @property
    def page_count(self) -> int | None:
        if self.pages is not None:
            return len(self.pages)
        return self.page_markers

    def warn(self, code: str, message: str, location: str | None = None) -> None:
        self.warnings.append(Warn(code, message, location))

    def note_unsupported(self, kind: str, count: int, detail: str) -> None:
        if count:
            self.unsupported.append(Construct(kind, count, detail))

    # -- the token stream every text check reads --------------------------------

    def stream(self, origins: frozenset[Origin]) -> list[Tok]:
        """Tokens of every block, in order, keeping only `origins`. UNKNOWN
        segments always survive the filter: an unreadable construct is never
        projected away, because dropping it would turn UNKNOWN into absent."""
        out: list[Tok] = []
        for bi, block in enumerate(self.blocks):
            pieces: list[str] = []
            owners: list[Origin] = []       # the origin of every character in "".join(pieces)
            for seg in block.segments:
                if seg.origin is Origin.UNKNOWN:
                    _flush(out, pieces, owners, bi, block.page)
                    where = block.locator or f"block {bi}"
                    out.append(Tok(Sentinel(seg.reason or "unresolved_content", where), "", (),
                                   bi, block.page, len(out), Origin.UNKNOWN))
                    continue
                if seg.origin not in origins:
                    # Excluded text is removed, not replaced by a space: a
                    # reference mark glued to a word ("footnote[1]") leaves the
                    # word the other format shows ("footnote").
                    continue
                piece = N.normalize(seg.text)
                pieces.append(piece)
                owners.extend([seg.origin] * len(piece))
            _flush(out, pieces, owners, bi, block.page)
        return out

    def list_items(self) -> list[Block]:
        """Every list item, whatever other role its block has."""
        return [b for b in self.blocks if b.kind is BlockKind.LIST_ITEM or b.list_item]

    def headings(self) -> list[Block]:
        return [b for b in self.blocks if b.kind is BlockKind.HEADING]


def _flush(out: list[Tok], pieces: list[str], owners: list[Origin], bi: int, page: int | None) -> None:
    """Tokenize the pending text of one block and empty the buffers."""
    if not pieces:
        return
    text = "".join(pieces)
    for m in _NON_SPACE.finditer(text):
        # NFC again per token: a combining mark split from its base letter
        # across two DOCX runs composes here, as it would in a format that
        # stored it as one string.
        tok = unicodedata.normalize("NFC", m.group(0))
        kinds = set(owners[m.start():m.end()])
        origin = kinds.pop() if len(kinds) == 1 else Origin.CONTENT
        c = N.core(tok)
        out.append(Tok(tok, c, N.classify(c), bi, page, len(out), origin))
    pieces.clear()
    owners.clear()
